export function getJobDef(jobId: ArchetypeId): JobDef {
  return JOBS[jobId];
}

export function getSkillDef(jobId: ArchetypeId, skillId: string): SkillDef | undefined {
  return JOBS[jobId]?.skills.find((s) => s.id === skillId);
}

export function getEquipmentDef(equipId: string | null | undefined): EquipmentDef | undefined {
  if (!equipId) return undefined;
  return EQUIPMENT_CATALOG.find((e) => e.id === equipId);
}

export function computeHeroStats(hero: RosterHeroSave): StatBlock {
  const job = JOBS[hero.jobId];
  const lvlBonus = Math.max(0, hero.level - 1);

  const stats: StatBlock = {
    hp: Math.round(job.baseStats.hp + job.growthPerLevel.hp * lvlBonus),
    mp: Math.round(job.baseStats.mp + job.growthPerLevel.mp * lvlBonus),
    atk: Math.round(job.baseStats.atk + job.growthPerLevel.atk * lvlBonus),
    mag: Math.round(job.baseStats.mag + job.growthPerLevel.mag * lvlBonus),
    def: Math.round(job.baseStats.def + job.growthPerLevel.def * lvlBonus),
    speed: Math.round(job.baseStats.speed + job.growthPerLevel.speed * lvlBonus),
    move: job.baseStats.move,
    jump: job.baseStats.jump,
    evasion: job.baseStats.evasion,
    shieldBlock: job.baseStats.shieldBlock,
  };

  // Passive JP upgrades stack cleanly on top of base stats
  for (const pid of hero.passiveUpgrades) {
    const p = PASSIVE_UPGRADES[pid];
    if (p) {
      stats[p.stat] = (stats[p.stat] as number) + p.bonus;
    }
  }

  // Equipment modifier stack (computed purely from loadout IDs, zero drift on unequip)
  const slots = [
    hero.equipment.weapon,
    hero.equipment.shield,
    hero.equipment.armor,
    hero.equipment.accessory,
  ];
  for (const eqId of slots) {
    const eq = getEquipmentDef(eqId);
    if (!eq) continue;
    for (const [key, val] of Object.entries(eq.stats)) {
      const k = key as keyof StatBlock;
      if (typeof val === 'number') {
        stats[k] = Number((stats[k] + val).toFixed(3));
      }
    }
  }

  stats.evasion = Math.min(0.65, stats.evasion);
  stats.shieldBlock = Math.min(0.70, stats.shieldBlock);
  return stats;
}

export function computeEnemyStats(jobId: ArchetypeId, level: number, hpScale = 1, atkScale = 1): StatBlock {
  const job = JOBS[jobId];
  const lvlBonus = Math.max(0, level - 1);
  return {
    hp: Math.round((job.baseStats.hp + job.growthPerLevel.hp * lvlBonus) * hpScale),
    mp: Math.round(job.baseStats.mp + job.growthPerLevel.mp * lvlBonus),
    atk: Math.round((job.baseStats.atk + job.growthPerLevel.atk * lvlBonus) * atkScale),
    mag: Math.round((job.baseStats.mag + job.growthPerLevel.mag * lvlBonus) * atkScale),
    def: Math.round(job.baseStats.def + job.growthPerLevel.def * lvlBonus),
    speed: Math.round(job.baseStats.speed + job.growthPerLevel.speed * lvlBonus),
    move: job.baseStats.move,
    jump: job.baseStats.jump,
    evasion: job.baseStats.evasion,
    shieldBlock: job.baseStats.shieldBlock,
  };
}
